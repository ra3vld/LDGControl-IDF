const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.LDG_PREVIEW_URL || 'http://127.0.0.1:8776';
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const errors=[];
  try {
    const context=await browser.newContext({viewport:{width:1280,height:900},locale:'ru-RU'});
    const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
    const response=await page.goto(base);
    const shell=await response.text();
    assert(shell.includes('<html lang="en">'));
    assert(!/[А-Яа-яЁё]/.test(shell),'The initial shell must be English');
    await page.waitForFunction(()=>document.querySelector('#fwd').textContent==='42.5');
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    assert.equal(await page.locator('#language').getAttribute('aria-label'),'Switch to Russian');
    const antennas=page.locator('#settings-sections>details').nth(5);
    await antennas.locator('summary').click();await antennas.locator('form').waitFor({state:'visible'});
    const input=antennas.locator('input[name=ant1_name]');await input.fill('Field antenna');
    assert.equal(await antennas.locator('select').first().locator('option').first().textContent(),'Leave unchanged');
    await antennas.locator('button[type=submit]').click();
    await page.waitForFunction(()=>!document.querySelector('#toast').hidden);
    assert.equal(await antennas.locator('.action-result').textContent(),'Check the entered values.');
    await page.locator('#language').click();
    assert.equal(await page.locator('html').getAttribute('lang'),'ru');
    assert.equal(await input.inputValue(),'Field antenna');
    assert.equal(await antennas.locator('select').first().locator('option').first().textContent(),'Не переключать');
    assert.equal(await antennas.locator('.action-result').textContent(),'Проверьте введённые значения.');
    assert.equal(await page.locator('#toast button').getAttribute('aria-label'),'Закрыть уведомление');
    assert.equal(await page.locator('#toast span').textContent(),'Проверьте введённые значения.');
    await page.reload();await page.locator('#settings-sections>details').last().waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'),'ru','Remember the explicit Russian choice');
    await page.locator('#language').click();await page.reload();await page.locator('#settings-sections>details').last().waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'),'en','Remember the explicit English choice');
    await page.evaluate(()=>localStorage.setItem('ldg.language','invalid-language'));await page.reload();
    await page.locator('#settings-sections>details').last().waitFor();assert.equal(await page.locator('html').getAttribute('lang'),'en');
    const blocked=await browser.newContext({locale:'ru-RU'});
    await blocked.addInitScript(()=>{
      Object.defineProperty(Storage.prototype,'getItem',{value(){throw new DOMException('Storage unavailable','SecurityError');}});
      Object.defineProperty(Storage.prototype,'setItem',{value(){throw new DOMException('Storage unavailable','SecurityError');}});
    });
    const restricted=await blocked.newPage();restricted.on('pageerror',e=>errors.push(e.message));
    await restricted.goto(base);await restricted.locator('#settings-sections>details').last().waitFor();
    assert.equal(await restricted.locator('html').getAttribute('lang'),'en');await restricted.locator('#language').click();assert.equal(await restricted.locator('html').getAttribute('lang'),'ru');
    await restricted.reload();await restricted.locator('#settings-sections>details').last().waitFor();assert.equal(await restricted.locator('html').getAttribute('lang'),'en');
    const releases=await context.newPage();releases.on('pageerror',e=>errors.push(e.message));
    await releases.route('**/api/v2/capabilities',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({api_version:2,board:'sunton',firmware:'0.1.0',release_repository:'example/LDGControl-IDF'})}));
    await releases.route('https://api.github.com/repos/example/LDGControl-IDF/releases/latest',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({tag_name:'v0.2.0',html_url:'https://example.invalid/release',assets:[{name:'sunton.manifest.json',url:'https://example.invalid/manifest',browser_download_url:'https://example.invalid/manifest'}]})}));
    await releases.goto(base);await releases.waitForFunction(()=>document.querySelector('#release-state').textContent==='Update available: v0.2.0');
    assert.equal(await releases.locator('#release-list button').textContent(),'Install release');
    await releases.locator('#language').click();
    assert.equal(await releases.locator('#release-state').textContent(),'Доступно обновление: v0.2.0');
    assert.equal(await releases.locator('#release-list button').textContent(),'Установить релиз');
    assert.deepEqual(errors,[]);
    await fs.mkdir('local-notes',{recursive:true});
    await fs.writeFile('local-notes/browser-language-results.json',JSON.stringify({englishShell:true,englishDefaultWithRussianBrowser:true,englishRussianSwitch:true,explicitLanguageRemembered:true,formsAndMessagesPreserved:true,lateOptionsTranslated:true,accessibleLabelsTranslated:true,invalidPreferenceDefaultsEnglish:true,storageFailureStillWorks:true,releaseMessagesAndButtonsTranslated:true,errors},null,2)+'\n');
    console.log('Default language, RU/EN switch, persistence, forms, messages, late options and storage fallback: PASS');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
